"""Phase 7-mini: deterministic @a11y / @security Playwright spec generator (no LLM).

Input: test_comprehension/app_map.json (+ requirements.json for NFR AC links, project.yaml for flags/login steps).
Output: test_creation/test_scripts/nfr/nfr_a11y.spec.ts and nfr_security_<origin>.spec.ts.
CLI: python -m tools.nonfunctional.generate <project_dir>
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

import yaml

from tools.requirements.classify import heuristic_testability

FIXTURE_IMPORT = "../../../../../_shared/runtime/fixtures/testFixture"
RULES_IMPORT = "../../../../../_shared/runtime/fixtures/securityRules"
ROLE_PREF = ("guest", "user")


def flags(project: dict) -> dict:
    tt = project.get("test_types") or {}
    return {"accessibility": bool(tt.get("accessibility")), "security_passive": bool(tt.get("security_passive"))}


def pick_states(app_map: dict) -> list[dict]:
    """One reachable state per url_template, preferring the least-privileged role."""
    best: dict[str, tuple[int, dict]] = {}
    for s in app_map.get("states", []):
        if s.get("access") == "blocked" or int(s.get("status") or 200) >= 400:
            continue
        roles = s.get("roles") or []
        rank = min((ROLE_PREF.index(r) for r in roles if r in ROLE_PREF), default=len(ROLE_PREF))
        key = s.get("url_template") or s["url"]
        if key not in best or rank < best[key][0]:
            best[key] = (rank, s)
    return [v[1] for v in best.values()]


def role_of(state: dict) -> str:
    roles = state.get("roles") or []
    for r in ROLE_PREF:
        if r in roles:
            return r
    return roles[0] if roles else "guest"


def nfr_ac_ids(requirements: dict | list, kind: str) -> list[str]:
    """AC ids whose text is non-functional and matches `kind` (accessibility|security)."""
    pat = re.compile(r"accessib|WCAG|screen reader|contrast" if kind == "accessibility"
                     else r"\bHSTS\b|\bCSP\b|\bcookie|\bHTTPS\b|security header|\btoken", re.I)
    reqs = requirements.get("requirements", []) if isinstance(requirements, dict) else requirements
    ids = []
    for r in reqs:
        for ac in r.get("acceptance_criteria", []):
            text = ac.get("statement", "")
            if pat.search(text) and (kind != "accessibility" or heuristic_testability(text)[0] == "non_functional"):
                ids.append(ac["id"])
    return ids


def _tags(kind: str, ac_ids: list[str]) -> str:
    return " ".join([f"@{kind}"] + ([f"@{a}" for a in ac_ids] if ac_ids else ["@nfr"]))


def _login(project: dict, role: str) -> str:
    steps = (((project.get("auth") or {}).get("roles") or {}).get(role) or {}).get("steps") or []
    lines = []
    for st in steps:
        if "goto" in st:
            lines.append(f"  await page.goto({json.dumps(st['goto'])});")
        elif "fill" in st:
            lines.append(f"  await page.locator({json.dumps(st['fill']['selector'])}).fill({json.dumps(st['fill']['value'])});")
        elif "click" in st:
            lines.append(f"  await page.locator({json.dumps(st['click'])}).click();")
        elif "wait" in st:
            lines.append(f"  await page.waitForTimeout({int(st['wait'])});")
    return "\n".join(lines)


def gen_a11y_spec(states: list[dict], project: dict, ac_ids: list[str]) -> str:
    out = [f"import {{ test, expect }} from '{FIXTURE_IMPORT}';", "",
           "// Generated by tools/nonfunctional/generate.py (Phase 7-mini) — do not edit.",
           "const BLOCKING = ['critical', 'serious'];", ""]
    for s in states:
        role = role_of(s)
        title = f"a11y: {s['url_template']} ({role}) {_tags('a11y', ac_ids)}"
        out.append(f"test({json.dumps(title)}, async ({{ page, a11y }}, testInfo) => {{")
        if role != "guest" and _login(project, role):
            out.append(_login(project, role))
        out += [f"  await page.goto({json.dumps(s['url'])});",
                "  const results = await a11y.scan({ tags: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] });",
                "  const v = (results.violations ?? []).map((x: any) => ({ id: x.id, impact: x.impact, help: x.help, nodes: x.nodes?.length ?? 0 }));",
                "  await testInfo.attach('a11y-violations.json', { body: JSON.stringify(v, null, 2), contentType: 'application/json' });",
                "  for (const w of v.filter((x: any) => !BLOCKING.includes(x.impact))) testInfo.annotations.push({ type: 'a11y-warning', description: `${w.id} (${w.impact})` });",
                "  expect(v.filter((x: any) => BLOCKING.includes(x.impact)), 'critical/serious a11y violations').toEqual([]);",
                "});", ""]
    return "\n".join(out)


def origin_of(url: str) -> str:
    p = urlsplit(url)
    return f"{p.scheme}://{p.netloc}"


def gen_security_spec(origin: str, states: list[dict], project: dict, ac_ids: list[str]) -> str:
    out = [f"import {{ test, expect }} from '{FIXTURE_IMPORT}';",
           f"import {{ checkHeaders, checkCookies, checkUrl, checkStorage }} from '{RULES_IMPORT}';", "",
           "// Generated by tools/nonfunctional/generate.py (Phase 7-mini) — passive checks only, no attack payloads.",
           f"const HTTPS = {str(origin.startswith('https')).lower()};", ""]
    for s in states:
        role = role_of(s)
        title = f"security: {s['url_template']} ({role}) {_tags('security', ac_ids)}"
        out.append(f"test({json.dumps(title)}, async ({{ page }}, testInfo) => {{")
        if role != "guest" and _login(project, role):
            out.append(_login(project, role))
        out += [f"  const resp = await page.goto({json.dumps(s['url'])});",
                "  const findings = [",
                "    ...checkHeaders(resp ? await resp.allHeaders() : {}, { https: HTTPS }),",
                "    ...checkCookies(await page.context().cookies(), { https: HTTPS }),",
                "    ...checkUrl(page.url()),",
                "    ...checkStorage(await page.evaluate(() => ({ ...localStorage })), 'localStorage'),",
                "  ];",
                "  await testInfo.attach('security-findings.json', { body: JSON.stringify(findings, null, 2), contentType: 'application/json' });",
                "  expect(findings, 'passive security findings').toEqual([]);",
                "});", ""]
    return "\n".join(out)


def generate(project_dir: Path, out_dir: Path | None = None) -> list[Path]:
    project_dir = Path(project_dir)
    project = yaml.safe_load((project_dir / "project.yaml").read_text(encoding="utf-8")) or {}
    f = flags(project)
    if not any(f.values()):
        return []
    comp = project_dir / "test_comprehension"
    app_map = json.loads((comp / "app_map.json").read_text(encoding="utf-8"))
    req_path = comp / "requirements.json"
    reqs = json.loads(req_path.read_text(encoding="utf-8")) if req_path.exists() else []
    out_dir = out_dir or project_dir / "test_creation" / "test_scripts" / "nfr"
    out_dir.mkdir(parents=True, exist_ok=True)
    states, written = pick_states(app_map), []
    if f["accessibility"]:
        p = out_dir / "nfr_a11y.spec.ts"
        p.write_text(gen_a11y_spec(states, project, nfr_ac_ids(reqs, "accessibility")), encoding="utf-8")
        written.append(p)
    if f["security_passive"]:
        ac = nfr_ac_ids(reqs, "security")
        origins: dict[str, list[dict]] = {}
        for s in states:
            origins.setdefault(origin_of(s["url"]), []).append(s)
        for origin, sts in origins.items():
            slug = re.sub(r"\W+", "_", urlsplit(origin).netloc).strip("_")
            p = out_dir / f"nfr_security_{slug}.spec.ts"
            p.write_text(gen_security_spec(origin, sts, project, ac), encoding="utf-8")
            written.append(p)
    return written


if __name__ == "__main__":
    for w in generate(Path(sys.argv[1])):
        print(w)
