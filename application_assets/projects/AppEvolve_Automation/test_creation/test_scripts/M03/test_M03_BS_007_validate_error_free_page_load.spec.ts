import { test, expect, Page } from '@playwright/test';
const BASE_URL = process.env.BASE_URL || 'https://pt-dev.appevolve.intuitive.ai/appevolve/dashboard';

test.describe.configure({ mode: 'serial' });

test.describe('Validate error-free page load (M03_BS_007)', () => {
  let page: Page;

  test.beforeAll(async ({ browser }) => {
    page = await browser.newPage();
    await page.goto("https://pt-dev.appevolve.intuitive.ai/");
    await page.locator("button:has-text('SSO Login')").click();
    await page.waitForTimeout(4000);
    await page.locator("#username").fill(process.env.APPEVOLVE_AUTOMATION_DEV_USERNAME ?? "");
    await page.locator("#password").fill(process.env.APPEVOLVE_AUTOMATION_DEV_PASSWORD ?? "");
    await page.locator("#kc-login").click();
    await page.waitForTimeout(2000);
    await page.locator("button.joyride__hurray-btn").click();
    await page.waitForTimeout(1000);
  });

  test.afterAll(async () => {
    await page.close();
  });

  test('positive — dashboard page loads without console errors', async () => {
    // Clear browser console before starting
    const consoleErrors: string[] = [];
    
    page.on('console', (msg) => {
      if (msg.type() === 'error') {
        consoleErrors.push(msg.text());
      }
    });

    // Navigate to dashboard page
    await page.goto(BASE_URL);
    
    // Wait for the page to fully load
    await page.waitForLoadState('networkidle');
    
    // Assert that no console errors occurred during page load
    await expect(consoleErrors.length, 'Dashboard page should load with zero console errors').toBe(0);
    
    // Additional verification that the page loaded successfully
    await expect(page, 'Dashboard URL should be loaded correctly').toHaveURL(/.*dashboard/);
  });
});